"""Migrations must build the exact schema of models.py (decision 46: PostgreSQL + SQLite, MySQL optional)."""
import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

CORE = Path(__file__).resolve().parents[1]


def cfg(url: str) -> Config:
    c = Config(str(CORE / "alembic.ini"))
    c.set_main_option("script_location", str(CORE / "migrations"))
    c.attributes["url"] = url
    return c


def _url(tmp_path):
    return os.environ.get("TULPORGO_TEST_DATABASE_URL") or f"sqlite+aiosqlite:///{(tmp_path / 'm.db').as_posix()}"


def test_upgrade_head_matches_models(tmp_path):
    c = cfg(_url(tmp_path))
    command.downgrade(c, "base")                         # clean slate also on a shared PostgreSQL test DB
    command.upgrade(c, "head")
    command.check(c)                                     # raises if models.py and migrations differ


def test_check_catches_unmigrated_model_change(tmp_path):
    # negative: add a column to the metadata without a migration → check must fail
    from sqlalchemy import Column, Integer
    from tulporgo_core.models import User
    c = cfg(_url(tmp_path))
    command.downgrade(c, "base")
    command.upgrade(c, "head")
    col = Column("tmp_unmigrated", Integer)
    User.__table__.append_column(col)
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(c)
    finally:
        User.__table__._columns.remove(col)
    command.downgrade(c, "base")


def test_trip_topic_columns_are_added_and_dropped_by_0002(tmp_path):
    from sqlalchemy import create_engine, inspect
    if os.environ.get("TULPORGO_TEST_DATABASE_URL"):
        pytest.skip("column inspection below is written for the SQLite file; other databases are covered by `check`")
    path = tmp_path / "t.db"
    c = cfg(f"sqlite+aiosqlite:///{path.as_posix()}")

    def trip_columns() -> dict:
        eng = create_engine(f"sqlite:///{path.as_posix()}")
        try:
            return {col["name"]: col for col in inspect(eng).get_columns("trips")}
        finally:
            eng.dispose()

    command.upgrade(c, "0001")
    assert "passenger_topic_id" not in trip_columns()
    command.upgrade(c, "0002")
    cols = trip_columns()
    assert cols["passenger_topic_id"]["nullable"] and cols["driver_topic_id"]["nullable"]
    command.downgrade(c, "0001")                         # negative: the downgrade really removes them again
    assert "passenger_topic_id" not in trip_columns() and "driver_topic_id" not in trip_columns()
    command.upgrade(c, "head")
    command.check(c)


def test_driver_documents_table_is_added_and_dropped_by_0003(tmp_path):
    from sqlalchemy import create_engine, inspect
    if os.environ.get("TULPORGO_TEST_DATABASE_URL"):
        pytest.skip("table inspection below is written for the SQLite file; other databases are covered by `check`")
    path = tmp_path / "d.db"
    c = cfg(f"sqlite+aiosqlite:///{path.as_posix()}")

    def inspected():
        eng = create_engine(f"sqlite:///{path.as_posix()}")
        try:
            insp = inspect(eng)
            if "driver_documents" not in insp.get_table_names():
                return None
            return ({col["name"] for col in insp.get_columns("driver_documents")},
                    [u["column_names"] for u in insp.get_unique_constraints("driver_documents")])
        finally:
            eng.dispose()

    command.upgrade(c, "0002")
    assert inspected() is None
    command.upgrade(c, "0003")
    cols, uniques = inspected()
    assert {"driver_id", "kind", "content_type", "size", "sha256", "data_encrypted", "created_at"} <= cols
    assert ["driver_id", "kind"] in uniques
    command.downgrade(c, "0002")                         # negative: the downgrade really drops the table
    assert inspected() is None
    command.upgrade(c, "head")
    command.check(c)


