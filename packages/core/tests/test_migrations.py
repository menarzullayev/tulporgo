"""Migrations must build the exact schema of models.py (decision 46: PostgreSQL + SQLite, MySQL optional)."""
import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

CORE = Path(__file__).resolve().parents[1]


def cfg(url: str) -> Config:
    c = Config(str(CORE / "alembic.ini"))
    c.set_main_option("script_location", str(CORE / "migrations"))
    c.attributes["url"] = url
    return c


def _url(tmp_path):
    return os.environ.get("TULPORGO_TEST_DATABASE_URL") or f"sqlite+aiosqlite:///{(tmp_path / 'm.db').as_posix()}"


def test_upgrade_head_matches_models(tmp_path):
    c = cfg(_url(tmp_path))
    command.downgrade(c, "base")                         # clean slate also on a shared PostgreSQL test DB
    command.upgrade(c, "head")
    command.check(c)                                     # raises if models.py and migrations differ


def test_check_catches_unmigrated_model_change(tmp_path):
    # negative: add a column to the metadata without a migration → check must fail
    from sqlalchemy import Column, Integer
    from tulporgo_core.models import User
    c = cfg(_url(tmp_path))
    command.downgrade(c, "base")
    command.upgrade(c, "head")
    col = Column("tmp_unmigrated", Integer)
    User.__table__.append_column(col)
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(c)
    finally:
        User.__table__._columns.remove(col)
    command.downgrade(c, "base")
